-- Базовая версия согласия до введения версионирования.
--
-- migrations/012 создавала таблицу с DEFAULT '1.0' и записывала это значение
-- всем существующим пользователям; старый бэкенд подставлял '1.0', когда клиент
-- не передавал версию. В интерфейсе повторного согласия это читалось как
-- «предыдущая версия 1.0», хотя никакой редакции 1.0 не существовало.
--
-- Приводим базовое значение к осмысленному 0.1. Актуальные версии документов
-- живут в apps/web/src/lib/legal/config.ts (LEGAL_VERSIONS) — здесь только
-- «доисторическое» значение для записей без явной версии.
--
-- Обе операции идемпотентны: повторный прогон (например, если файл применили
-- вручную до первого запуска бэкенда) ничего не меняет.

ALTER TABLE user_terms_acceptance
    ALTER COLUMN terms_version SET DEFAULT '0.1';

UPDATE user_terms_acceptance
SET terms_version = '0.1'
WHERE terms_version = '1.0';
